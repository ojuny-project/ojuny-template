#!/usr/bin/env bash
set -euo pipefail

template="${OJUNY_TEMPLATE_SOURCE:-}"
root=""
hostname="ojuny"
username="user"
fullname="Primary account"
disk=""
firmware="efi"
state_version="26.11"
password=""
hashed_password=""
ssh_keys=()
force=0

usage() {
  cat <<'EOF'
Usage: prepare-remote-repository [options]

Create a template repository with a disko layout and a generic hardware module,
ready for nixos-anywhere. The user and host pages are generated by the template
prepare-repo script.

Options:
  --template URL|PATH  Template to copy (default: the running template)
  --root DIR           Destination repository (default: ./ojuny-deploy)
  --hostname NAME      Host name (default: ojuny)
  --username NAME      Account name (default: user)
  --full-name NAME     Account description
  --disk DEVICE        Target disk, preferably /dev/disk/by-id/...
  --firmware efi|bios  Target firmware (default: efi)
  --state-version VER  NixOS state version (default: 26.11)
  --password PASS      Account password (prompted when omitted)
  --hashed-password H  Pre-hashed account password
  --ssh-key KEY        SSH public key, repeatable
  --force              Replace a non-empty destination
  -h, --help           Show this help
EOF
}

while [ "$#" -gt 0 ]; do
  case "$1" in
    --template)
      template="${2:-}"
      shift 2
      ;;
    --root)
      root="${2:-}"
      shift 2
      ;;
    --hostname)
      hostname="${2:-}"
      shift 2
      ;;
    --username)
      username="${2:-}"
      shift 2
      ;;
    --full-name)
      fullname="${2:-}"
      shift 2
      ;;
    --disk)
      disk="${2:-}"
      shift 2
      ;;
    --firmware)
      firmware="${2:-}"
      shift 2
      ;;
    --state-version)
      state_version="${2:-}"
      shift 2
      ;;
    --password)
      password="${2:-}"
      shift 2
      ;;
    --hashed-password)
      hashed_password="${2:-}"
      shift 2
      ;;
    --ssh-key)
      ssh_keys+=("${2:-}")
      shift 2
      ;;
    --force)
      force=1
      shift
      ;;
    -h | --help)
      usage
      exit 0
      ;;
    *)
      echo "prepare-remote-repository: unknown argument: $1" >&2
      usage >&2
      exit 2
      ;;
  esac
done

if [ -z "$template" ]; then
  echo "prepare-remote-repository: no template given and no template source available" >&2
  exit 2
fi
if [ -z "$disk" ]; then
  echo "prepare-remote-repository: --disk is required" >&2
  exit 2
fi
if [ -z "$root" ]; then
  root="$PWD/ojuny-deploy"
fi
case "$firmware" in
  efi | bios) ;;
  *)
    echo "prepare-remote-repository: --firmware must be efi or bios" >&2
    exit 2
    ;;
esac

work_dir="$(mktemp -d)"
trap 'rm -rf "$work_dir"' EXIT

template_ref="$template"
case "$template" in
  http://* | https://* | git+* | ssh://* | git@*)
    echo "cloning $template"
    git clone --depth 1 "$template" "$work_dir/template"
    template="$work_dir/template"
    template_ref="path:$template"
    ;;
  /*)
    template_ref="path:$template"
    ;;
esac

if [ -z "$hashed_password" ]; then
  if [ -z "$password" ] && [ -t 0 ]; then
    read -r -s -p "Account password: " password
    echo
  fi
  if [ -n "$password" ]; then
    hashed_password="$(mkpasswd -m yescrypt -- "$password" 2>/dev/null || mkpasswd -m sha-512 -- "$password")"
  else
    hashed_password="!"
  fi
fi

for index in "${!ssh_keys[@]}"; do
  if [ -f "${ssh_keys[$index]}" ]; then
    ssh_keys[$index]="$(cat "${ssh_keys[$index]}")"
  fi
done

if [ "$hashed_password" = "!" ] && [ "${#ssh_keys[@]}" -eq 0 ]; then
  echo "prepare-remote-repository: provide --password, --hashed-password or --ssh-key" >&2
  exit 2
fi

prepare_args=(
  --root "$root"
  --template "$template"
  --username "$username"
  --fullname "$fullname"
  --hostname "$hostname"
  --state-version "$state_version"
  --hashed-password "$hashed_password"
  --non-interactive
)
if [ "$force" -eq 1 ]; then
  prepare_args+=(--force)
fi

nix run "$template_ref#prepare-repo" -- "${prepare_args[@]}"

helper="$root/scripts/flake_structure.py"
user_file="$(python3 "$helper" --root "$root" --non-interactive path --module users --fallback modules/00-user.nix)"
hardware_file="$(python3 "$helper" --root "$root" --non-interactive path --module hardware --fallback modules/00-hardware.nix)"

if [ "${#ssh_keys[@]}" -gt 0 ]; then
  keys="[\n"
  for key in "${ssh_keys[@]}"; do
    keys+="          \"$key\"\n"
  done
  keys+="        ]"
  sed -i "s|openssh.authorizedKeys.keys = \[ \];|openssh.authorizedKeys.keys = $keys;|" \
    "$user_file"
fi

mkdir -p "$(dirname "$hardware_file")"

if [ "$firmware" = "efi" ]; then
  efi=true
  bios=false
else
  efi=false
  bios=true
fi

cat >"$hardware_file" <<EOF
{ self, inputs, ... }: {

  flake.modules.nixos.system-hardware =
    { lib, ... }:
    {
      imports = [ inputs.disko.nixosModules.disko ];

      boot.initrd.availableKernelModules = [
        "ahci"
        "dm_mod"
        "hid_generic"
        "nvme"
        "sd_mod"
        "sr_mod"
        "usb_storage"
        "usbhid"
        "xhci_pci"
      ];

      disko.devices.disk.main = {
        device = "$disk";
        type = "disk";
        content = {
          type = "gpt";
          partitions = {
            boot = {
              size = "1M";
              type = "EF02";
              priority = 1;
            };
            ESP = {
              size = "1G";
              type = "EF00";
              priority = 2;
              content = {
                type = "filesystem";
                format = "vfat";
                mountpoint = "/boot";
                mountOptions = [ "umask=0077" ];
              };
            };
            root = {
              size = "100%";
              priority = 4;
              content = {
                type = "filesystem";
                format = "ext4";
                mountpoint = "/";
              };
            };
          };
        };
      };

      boot.loader.systemd-boot.enable = lib.mkForce $efi;
      boot.loader.efi.canTouchEfiVariables = lib.mkForce $efi;
      boot.loader.grub.enable = lib.mkForce $bios;
      boot.loader.grub.devices = lib.mkIf $bios [ "$disk" ];
      boot.loader.grub.efiSupport = lib.mkForce $efi;
      boot.loader.grub.efiInstallAsRemovable = lib.mkForce $efi;

      ojuny.network.deploy-rs.enable = lib.mkDefault true;

      nixpkgs.hostPlatform = lib.mkDefault "x86_64-linux";
    };

  flake.modules.nixos.system-bootloader =
    { lib, ... }:
    {
      boot.loader.systemd-boot.enable = lib.mkDefault false;
      boot.loader.efi.canTouchEfiVariables = lib.mkDefault false;
      boot.loader.grub.enable = lib.mkDefault false;
      boot.loader.grub.devices = lib.mkDefault [ ];
    };

}
EOF

quirks="$(python3 "$helper" --root "$root" --non-interactive path --module quirks --fallback modules/backend/00-hardware-quirks.nix)"
imports=(--name system-configuration --name users --name system-hardware --name system-bootloader)
if [ -f "$quirks" ]; then
  imports+=(--name system-hardware-quirks)
fi
python3 "$helper" --root "$root" --non-interactive ensure-imports "${imports[@]}" >/dev/null

git -C "$root" init -q
git -C "$root" add -A
git -C "$root" -c user.name="Ojuny Installer" \
  -c user.email="installer@ojuny.local" \
  commit -qm "Prepare the remote installation layout"

echo
echo "repository: $root"
echo "host: $hostname"
echo "disk: $disk"
echo "firmware: $firmware"
